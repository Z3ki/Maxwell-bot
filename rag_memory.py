    async def update_shared_context(self, context_id: str, updates: dict) -> bool:
        sets = []
        params = []
        for key in ("content", "scope", "importance"):
            if key in updates:
                sets.append(f"{key}=?")
                params.append(updates[key])
        if not sets:
            return False
        sets.append("embedding=NULL")  # force re-embed if content changed
        params.append(str(context_id))
        cursor = self._db.execute(
            f"UPDATE vectors SET {', '.join(sets)} WHERE id=? AND kind='shared_context'",
            params,
        )
        if cursor.rowcount > 0:
            if "content" in updates:
                asyncio.ensure_future(
                    self._embed_and_store(str(context_id), str(updates["content"]))
                )
            return True
        return False

