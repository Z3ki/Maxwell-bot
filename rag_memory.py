    async def apply_ltm_batch(self, ops: list[dict]) -> dict:
        """Apply batch LTM operations (add/edit/delete)."""
        added = 0
        edited = 0
        deleted = 0
        errors = 0
        for op in ops:
            try:
                kind = str(op.get("kind") or op.get("op") or "")
                if kind == "add":
                    content = str(op.get("content") or "")
                    if content:
                        await self.add_long_term_memory(content)
                        added += 1
                elif kind == "edit":
                    mid = str(op.get("id") or "")
                    content = str(op.get("content") or "")
                    if mid and content:
                        if await self.edit_long_term_memory(mid, content):
                            edited += 1
                        else:
                            errors += 1
                elif kind == "delete":
                    mid = str(op.get("id") or "")
                    if mid:
                        if await self.remove_long_term_memory(mid):
                            deleted += 1
                        else:
                            errors += 1
            except Exception as e:
                logger.warning(f"LTM batch op failed: {e}")
                errors += 1
        return {"added": added, "edited": edited, "deleted": deleted, "errors": errors}

