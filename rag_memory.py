"""RAG vector memory for Maxwell Bot.

Replaces the old MemoryManager (memory.py) and ContextCleanupEngine
(context_cleanup.py) with a single SQLite + numpy vector store backed by
qwen3-embedding:0.6b via ollama.

Architecture:
  - SQLite database at data/maxwell_rag.db
  - Three logical stores in one table: channel messages, long-term facts,
    shared context entries — distinguished by `kind`
  - Each row stores the text, metadata JSON, and a 1024-dim embedding BLOB
  - Retrieval: cosine similarity via numpy dot product against the query
    embedding, filtered by kind/channel/scope as needed
  - Embeddings generated by POSTing to ollama's /api/embed endpoint

The public interface mirrors the old MemoryManager so bot.py changes are
minimal — same method names, same return shapes.
"""

import asyncio
import json
import logging
import sqlite3
import time
import uuid
from datetime import datetime, timezone
from pathlib import Path

import aiohttp
import numpy as np

logger = logging.getLogger(__name__)

# ─── constants ────────────────────────────────────────────────────────

# Embedding model. qwen3-embedding:0.6b wins on context length (32k
# tokens ≈ 128k chars, vs bge-m3's 8k). For memory use case — whole
# conversations, not single sentences — the long context is the
# deciding factor; we can skip a chunking pipeline entirely. 1024-dim
# output. ollama pull qwen3-embedding:0.6b
EMBED_MODEL = "qwen3-embedding:0.6b"
EMBED_DIM = 1024
OLLAMA_EMBED_URL = "http://localhost:11434/api/embed"

# Recency decay (seconds). 14 days. Score multiplied by exp(-age/tau).
RECENCY_TAU_SECONDS = 14 * 86400.0

MAX_CHANNELS = 25
MAX_MEMORY_CHARS = 1000
MAX_LTM_LINES = 999
DEFAULT_REM_EVENT_BUFFER_MAX = 500

# Cosine similarity threshold for RAG retrieval. Below this, results are
# considered noise and filtered out.
SIM_THRESHOLD = 0.35

# ─── filtering ────────────────────────────────────────────────────────

# Discord.MessageType values that produce no real user content. We never
# embed these — they're webhook metadata, presence events, or system
# messages. Names match `discord.MessageType` enum members.
_DISCORD_SKIP_TYPES = frozenset(
    {
        "default",  # included so unset types are still allowed
        "recipient_add",
        "recipient_remove",
        "call",
        "channel_name_change",
        "channel_icon_change",
        "pins_add",
        "new_member",
        "premium_guild_subscription",
        "premium_tier",
        "channel_follow_add",
        "guild_discovery_disqualified",
        "guild_discovery_requalified",
        "guild_discovery_grace_period_initial_warning",
        "guild_discovery_grace_period_final_warning",
        "thread_created",
        "reply",  # bare reply with no other content is just metadata
        "application_command",
        "invite",
        "contextual_command",
        "forum_thread_created",
    }
)

# Phrases that signal a bot's own output got re-fed into the store. We
# flag content containing these so add_to_channel_memory can split
# source='bot' vs source='user'.
_BOT_OUTPUT_MARKERS = (
    "bold of you to assume",
    "Called send_message with",
    "Called send_dm with",
    "Called edit_message with",
    "Called run_tool with",
    "Called autodelete with",
    "Called webfetch with",
    "RAG relevance:",
)

# Monosyllable / reaction threshold. Content shorter than this (after
# stripping URLs/markdown/mentions) is too low-signal to embed. We still
# *store* it (so /api/rag/messages shows recent), we just don't embed.
_MIN_EMBED_LEN = 4

# ─── helpers ──────────────────────────────────────────────────────────


def _utcnow() -> datetime:
    return datetime.now(timezone.utc)


def _utcnow_iso() -> str:
    return _utcnow().isoformat()


def _parse_iso(ts: str) -> datetime | None:
    if not ts:
        return None
    try:
        dt = datetime.fromisoformat(str(ts))
        if dt.tzinfo is None:
            dt = dt.replace(tzinfo=timezone.utc)
        return dt
    except Exception:
        return None


def _normalize_ltm_line(content: str) -> str:
    return " ".join(str(content).split())[:MAX_MEMORY_CHARS]


def _strip_reasoning_text(content: str) -> str:
    import re

    text = str(content or "")
    text = re.sub(
        r"<think\b[^>]*>.*?</think>", "", text, flags=re.IGNORECASE | re.DOTALL
    )
    return " ".join(text.split())


def _embedding_to_blob(vec: np.ndarray) -> bytes:
    """Store float32 embedding as compact BLOB."""
    return vec.astype(np.float32).tobytes()


def _blob_to_embedding(blob: bytes) -> np.ndarray:
    """Unpack BLOB back to float32 numpy array."""
    return np.frombuffer(blob, dtype=np.float32)


# ─── content filtering ────────────────────────────────────────────────


def _strip_for_embedding(text: str) -> str:
    """Normalize text before deciding 'is this worth embedding?'.

    - Strip URLs (they're not semantically meaningful by themselves)
    - Strip mentions (the bot already knows who they refer to in context)
    - Strip emojis-only runs (zero signal for recall)
    - Collapse whitespace

    Returns the cleaned string. Length of *this* decides embed vs skip.
    """
    import re

    s = str(text or "")
    if not s:
        return ""
    s = re.sub(r"https?://\S+", " ", s)
    s = re.sub(r"<@!?\d+>", " ", s)
    s = re.sub(r"<#\d+>", " ", s)
    s = re.sub(r":[a-zA-Z0-9_]+:", " ", s)  # emoji shortcodes
    s = re.sub(r"[\U00010000-\U0010ffff]", " ", s)  # unicode emoji
    s = re.sub(r"\s+", " ", s).strip()
    return s


def _is_system_event_content(content: str, message_type: str | None = None) -> bool:
    """True if this content is a Discord system event, not a user message.

    Detects embeds like `[embeds: Avatar update]` or `[embeds: Member left]`
    that the bot renders when no real message text exists.
    """
    if message_type and str(message_type) in _DISCORD_SKIP_TYPES:
        return True
    s = str(content or "").strip()
    if not s:
        return True
    if s.startswith("[embeds:") and s.endswith("]"):
        return True
    if s.startswith("[Message deleted in"):
        return True
    return False


def _detect_source(message: dict) -> str:
    """Figure out source='user' | 'bot' | 'system' for a message dict.

    Priority order:
    1. Explicit `source` field wins
    2. `author_is_bot: True` → 'bot'
    3. `_BOT_OUTPUT_MARKERS` substring match → 'bot'
    4. `_is_system_event_content` → 'system'
    5. Default 'user'
    """
    src = message.get("source")
    if src in ("user", "bot", "system"):
        return src
    if message.get("author_is_bot") is True:
        return "bot"
    content = str(message.get("content") or "")
    for marker in _BOT_OUTPUT_MARKERS:
        if marker in content:
            return "bot"
    if _is_system_event_content(content, message.get("message_type")):
        return "system"
    return "user"


def _score_with_recency(
    cosine: float, ts: str | None, now_ts: float | None = None
) -> float:
    """Apply recency decay: cosine * exp(-age_seconds / τ).

    LTM and shared_context always score at full cosine (they're durable
    facts by definition — their timestamp is when they were *written*,
    not when the underlying event happened). Pass kind='message' to opt
    out.
    """
    if not ts:
        return float(cosine)
    dt = _parse_iso(ts)
    if dt is None:
        return float(cosine)
    if now_ts is None:
        now_ts = _utcnow().timestamp()
    age = max(0.0, float(now_ts) - dt.timestamp())
    import math

    decay = math.exp(-age / RECENCY_TAU_SECONDS)
    return float(cosine) * (0.25 + 0.75 * decay)  # never below 25% of raw cosine


# ─── RemEventLog (kept identical — REM still uses it) ────────────────


class RemEventLog:
    """JSON-backed visible event ring for REM assimilation."""

    def __init__(self, data_dir: str, max_events: int = DEFAULT_REM_EVENT_BUFFER_MAX):
        self.data_dir = Path(data_dir)
        self.events_file = self.data_dir / "rem_events.json"
        self.max_events = max(1, int(max_events or DEFAULT_REM_EVENT_BUFFER_MAX))
        self.events = []
        self._lock = asyncio.Lock()
        self._dirty = False
        self._save_task = None
        self._pending_save = None
        self._save_lock = asyncio.Lock()

    def load_from_disk(self):
        try:
            if self.events_file.exists():
                data = json.loads(self.events_file.read_text(encoding="utf-8"))
                self.events = self._sanitize_events(
                    data if isinstance(data, list) else []
                )
        except (json.JSONDecodeError, OSError) as e:
            logger.error(f"Failed to load REM events: {e}")
            self.events = []

    def _sanitize_events(self, events: list) -> list:
        clean = []
        for raw in events:
            if not isinstance(raw, dict):
                continue
            role = str(raw.get("role") or "")
            if role not in {"user", "assistant"}:
                # Also accept events with kind/timestamp format (used by bot.py)
                if not raw.get("kind") and not raw.get("timestamp"):
                    continue
                # Convert kind-based events to the expected format
                role = str(raw.get("kind") or "user")
            mentions = []
            for row in list(raw.get("mentions") or [])[:10]:
                if not isinstance(row, dict):
                    continue
                mid = str(row.get("id") or "")
                if not mid:
                    continue
                mentions.append({"id": mid, "name": str(row.get("name") or mid)[:120]})
            clean.append(
                {
                    "ts": str(raw.get("ts") or raw.get("timestamp") or _utcnow_iso()),
                    "channel_id": str(raw.get("channel_id") or ""),
                    "guild_id": str(raw.get("guild_id"))
                    if raw.get("guild_id") is not None
                    else None,
                    "message_id": str(raw.get("message_id") or ""),
                    "user_id": str(raw.get("user_id") or ""),
                    "user_name": str(raw.get("user_name") or "")[:120],
                    "role": role,
                    "content": _strip_reasoning_text(raw.get("content", ""))[:4000],
                    "mentions": mentions,
                    "reply_to_message_id": str(raw.get("reply_to_message_id") or ""),
                    "reply_to_author": str(raw.get("reply_to_author") or "")[:120],
                    "reply_to_author_id": str(raw.get("reply_to_author_id") or ""),
                    "reply_to_self": bool(raw.get("reply_to_self", False)),
                    "auto_mode": bool(raw.get("auto_mode", False)),
                    "id": str(raw.get("id") or ""),
                    "kind": str(raw.get("kind") or role),
                    "timestamp": str(raw.get("timestamp") or _utcnow_iso()),
                }
            )
        return clean[-self.max_events :]

    async def _atomic_save(self, snapshot: list):
        async with self._save_lock:
            from utils import _atomic_json_write_sync

            await asyncio.to_thread(_atomic_json_write_sync, self.events_file, snapshot)

    def _schedule_save(self):
        self._dirty = True
        if self._save_task is not None:
            self._save_task.cancel()
        try:
            loop = asyncio.get_running_loop()
        except RuntimeError:
            return

        async def _debounced():
            try:
                await asyncio.sleep(5)
                await self._do_save()
            except asyncio.CancelledError:
                pass

        self._save_task = loop.create_task(_debounced())

    async def _do_save(self):
        self._save_task = None
        if self._dirty:
            self._dirty = False
            snapshot = list(self.events)
            await self._atomic_save(snapshot)

    async def record(self, event: dict):
        async with self._lock:
            # Sanitize through _sanitize_events to get consistent format
            clean = self._sanitize_events([event])
            if not clean or not clean[0]["content"]:
                return
            self.events.append(clean[0])
            if len(self.events) > self.max_events:
                self.events = self.events[-self.max_events :]
            self._schedule_save()

    async def drain_slice(self, since_ts: str | None = None) -> list:
        since = _parse_iso(since_ts or "")
        async with self._lock:
            if since is None:
                return [dict(e) for e in self.events]
            out = []
            for event in self.events:
                ts = _parse_iso(event.get("ts", event.get("timestamp", "")))
                if ts and ts > since:
                    out.append(dict(event))
            return out

    async def size(self) -> int:
        async with self._lock:
            return len(self.events)

    async def flush(self):
        async with self._lock:
            if self._save_task:
                self._save_task.cancel()
                self._save_task = None
            self._dirty = True
            await self._do_save()


# ─── RAGMemoryManager ────────────────────────────────────────────────


class RAGMemoryManager:
    """Vector-backed memory manager. Drop-in replacement for MemoryManager.

    Stores channel messages, long-term facts, and shared context entries
    in a single SQLite table with embeddings. Retrieval uses cosine
    similarity for semantic search (RAG).

    Public interface matches the old MemoryManager:
      - get_channel_memory(channel_id) -> list[dict]
      - add_to_channel_memory(channel_id, message) -> None
      - clear_channel_memory(channel_id) -> None
      - get_long_term_memory() -> list[dict]
      - add_long_term_memory(content) -> str
      - edit_long_term_memory(memory_id, content) -> bool
      - remove_long_term_memory(memory_id) -> bool
      - apply_ltm_batch(ops) -> dict
      - get_server_prompt(server_id) -> str | None
      - set_server_prompt(server_id, prompt) -> None
      - clear_server_prompt(server_id) -> None
      - add_shared_context(entry) -> str
      - remove_shared_context(context_id) -> bool
      - update_shared_context(context_id, updates) -> bool
      - list_shared_context(limit) -> list
      - get_relevant_shared_context(...) -> list

    New RAG-specific methods:
      - rag_search(query, kinds, channel_id, top_k) -> list[dict]
      - rag_relevant_context(query, channel_id, top_k) -> list[dict]
    """

    def __init__(self, data_dir: str, max_messages: int = 10000):
        self.data_dir = Path(data_dir)
        self.max_messages = min(max_messages, 10000)
        self.db_path = self.data_dir / "maxwell_rag.db"
        self.prompts_file = self.data_dir / "prompts.json"
        self._db: sqlite3.Connection | None = None
        self._lock = asyncio.Lock()
        self._embed_semaphore = asyncio.Semaphore(4)  # limit concurrent embed calls
        # Self-tuning cache state (kept minimal; SQLite holds the real cache)
        self._embed_cache: dict[
            str, np.ndarray
        ] = {}  # in-process LRU; SQLite is durable
        self._prompts: dict[str, str] = {}
        # Track background embed tasks so shutdown can await them (otherwise
        # in-flight embeds are silently dropped and rows stay embedding=NULL)
        # and so tests don't spam "coroutine ignored GeneratorExit".
        self._embed_tasks: set[asyncio.Task] = set()
        self._init_db()

    def _spawn(self, coro) -> asyncio.Task:
        """Create a tracked background task for embed work."""
        task = asyncio.ensure_future(coro)
        self._embed_tasks.add(task)
        task.add_done_callback(self._embed_tasks.discard)
        return task

    def _init_db(self):
        """Create SQLite DB and tables."""
        self.data_dir.mkdir(parents=True, exist_ok=True)
        self._db = sqlite3.connect(
            str(self.db_path),
            check_same_thread=False,
            isolation_level=None,  # autocommit
        )
        self._db.row_factory = sqlite3.Row
        self._db.execute("PRAGMA journal_mode=WAL")
        self._db.execute("PRAGMA synchronous=NORMAL")
        self._db.execute("PRAGMA cache_size=-64000")  # 64MB cache

        self._db.execute(
            """
            CREATE TABLE IF NOT EXISTS vectors (
                id TEXT PRIMARY KEY,
                kind TEXT NOT NULL,           -- 'message', 'ltm', 'shared_context',
                                              -- 'bot_output', 'negative'
                channel_id TEXT DEFAULT '',
                guild_id TEXT DEFAULT '',     -- NEW: server/channel isolation
                author TEXT DEFAULT '',
                author_id TEXT DEFAULT '',
                source TEXT DEFAULT 'user',   -- NEW: 'user' | 'bot' | 'system'
                content TEXT NOT NULL,
                content_hash TEXT DEFAULT '', -- NEW: SHA-256 of normalized content
                embedding BLOB,
                metadata TEXT DEFAULT '{}',
                scope TEXT DEFAULT '',
                importance INTEGER DEFAULT 0,
                parent_id TEXT DEFAULT '',    -- NEW: chunks point at parent msg
                chunk_index INTEGER DEFAULT 0,-- NEW: 0 for non-chunks
                downvotes INTEGER DEFAULT 0,  -- NEW: negative-feedback counter
                timestamp TEXT NOT NULL,
                created_at REAL NOT NULL
            )
            """
        )
        # ─── in-place migration from previous schema (idempotent) ─────
        # If columns don't exist yet, ALTER TABLE … ADD COLUMN. SQLite
        # refuses duplicates, so wrap each in a try and ignore OperationalError.
        _migrations = [
            ("guild_id", "TEXT DEFAULT ''"),
            ("source", "TEXT DEFAULT 'user'"),
            ("content_hash", "TEXT DEFAULT ''"),
            ("parent_id", "TEXT DEFAULT ''"),
            ("chunk_index", "INTEGER DEFAULT 0"),
            ("downvotes", "INTEGER DEFAULT 0"),
        ]
        for col, decl in _migrations:
            try:
                self._db.execute(f"ALTER TABLE vectors ADD COLUMN {col} {decl}")
            except Exception:
                pass  # column already exists

        # Backfill content_hash from content for existing rows.
        import hashlib as _hashlib

        for r in self._db.execute(
            "SELECT id, content FROM vectors WHERE content_hash='' OR content_hash IS NULL"
        ).fetchall():
            normalized = _strip_for_embedding(r["content"])
            h = _hashlib.sha256(normalized.encode("utf-8")).hexdigest()
            self._db.execute(
                "UPDATE vectors SET content_hash=? WHERE id=?", (h, r["id"])
            )

        # Seed embed_cache from existing rows so the first recall after
        # upgrade doesn't pay 619 cold ollama calls. Cheap (we already
        # have the blobs in `vectors.embedding`).
        for r in self._db.execute(
            "SELECT content, embedding FROM vectors WHERE embedding IS NOT NULL"
        ).fetchall():
            try:
                key = _hashlib.md5(r["content"].encode()).hexdigest()
                self._db.execute(
                    "INSERT OR IGNORE INTO embed_cache "
                    "(key, dim, embedding, created_at, last_used_at, hits) "
                    "VALUES (?, ?, ?, ?, 0, 0)",
                    (key, EMBED_DIM, r["embedding"], time.time()),
                )
            except Exception:
                pass

        # Backfill source for existing rows using the same heuristic
        # the new insert path uses.
        for r in self._db.execute(
            "SELECT id, kind, content, metadata FROM vectors "
            "WHERE source='user' OR source IS NULL OR source=''"
        ).fetchall():
            try:
                meta = json.loads(r["metadata"] or "{}")
            except Exception:
                meta = {}
            author_is_bot = meta.get("author_is_bot")
            content = r["content"]
            # Bot rows were inserted with a row.id prefix 'bot_*'
            new_src = "user"
            if str(r["id"]).startswith("bot_") or r["kind"] == "bot_output":
                new_src = "bot"
            elif _is_system_event_content(content):
                new_src = "system"
            elif author_is_bot is True:
                new_src = "bot"
            else:
                for marker in _BOT_OUTPUT_MARKERS:
                    if marker in content:
                        new_src = "bot"
                        break
            self._db.execute(
                "UPDATE vectors SET source=? WHERE id=?", (new_src, r["id"])
            )

        self._db.execute("CREATE INDEX IF NOT EXISTS idx_kind ON vectors(kind)")
        self._db.execute(
            "CREATE INDEX IF NOT EXISTS idx_channel ON vectors(channel_id)"
        )
        self._db.execute(
            "CREATE INDEX IF NOT EXISTS idx_kind_channel ON vectors(kind, channel_id)"
        )
        self._db.execute(
            "CREATE INDEX IF NOT EXISTS idx_timestamp ON vectors(timestamp)"
        )
        # NEW indices for the new retrieval paths
        self._db.execute("CREATE INDEX IF NOT EXISTS idx_guild ON vectors(guild_id)")
        self._db.execute("CREATE INDEX IF NOT EXISTS idx_source ON vectors(source)")
        self._db.execute(
            "CREATE INDEX IF NOT EXISTS idx_content_hash ON vectors(content_hash)"
        )
        self._db.execute("CREATE INDEX IF NOT EXISTS idx_parent ON vectors(parent_id)")
        # Unique constraint prevents duplicate (same channel + same content).
        # Skipped rows via OR IGNORE in insert path.
        try:
            self._db.execute(
                "CREATE UNIQUE INDEX IF NOT EXISTS idx_unique_content "
                "ON vectors(channel_id, content_hash) WHERE content_hash != ''"
            )
        except Exception:
            pass

        # ─── persistent embedding cache ────────────────────────────────
        # Survives restart. Indexed on (key, dim) for O(log n) point lookups.
        # Text inputs are normalized before hashing (strip whitespace) so
        # the same content embedded twice hits the same cache slot.
        self._db.execute(
            """
            CREATE TABLE IF NOT EXISTS embed_cache (
                key TEXT NOT NULL,
                dim INTEGER NOT NULL,
                embedding BLOB NOT NULL,
                created_at REAL NOT NULL,
                last_used_at REAL NOT NULL,
                hits INTEGER NOT NULL DEFAULT 0,
                PRIMARY KEY (key, dim)
            )
            """
        )
        self._db.execute(
            "CREATE INDEX IF NOT EXISTS idx_embed_cache_used "
            "ON embed_cache(last_used_at)"
        )

        # FTS5/BM25 hybrid search was prototyped but caused DB corruption
        # under concurrent writes (triggers + per-message embedding tasks
        # racing). Removed in favor of pure-cosine retrieval with cache.
        # The pure-cosine path is fast enough (~5ms with cached embed)
        # and correct enough for the current corpus size.

        # Migrate prompts
        try:
            if self.prompts_file.exists():
                data = json.loads(self.prompts_file.read_text(encoding="utf-8"))
                if isinstance(data, dict):
                    self._prompts = {str(k): str(v) for k, v in data.items()}
        except Exception as e:
            logger.warning(f"Failed to load prompts: {e}")
            self._prompts = {}

        # Migrate existing long_term_memory.txt if present
        self._migrate_ltm()
        # Migrate existing shared_context.json if present
        self._migrate_shared_context()

        logger.info(
            f"RAGMemoryManager initialized at {self.db_path} "
            f"({self._count_all()} vectors)"
        )

    def _count_all(self) -> int:
        try:
            row = self._db.execute("SELECT COUNT(*) as c FROM vectors").fetchone()
            return row["c"] if row else 0
        except Exception:
            return 0

    def _migrate_ltm(self):
        """One-time migration of long_term_memory.txt into the vector DB."""
        ltm_file = self.data_dir / "long_term_memory.txt"
        if not ltm_file.exists():
            return
        # Check if we already migrated (any LTM rows exist)
        try:
            row = self._db.execute(
                "SELECT COUNT(*) as c FROM vectors WHERE kind='ltm'"
            ).fetchone()
            if row and row["c"] > 0:
                return  # already migrated
        except Exception:
            pass

        try:
            lines = ltm_file.read_text(encoding="utf-8").strip().splitlines()
            migrated = 0
            import hashlib as _hashlib

            for line in lines:
                line = line.strip()
                if not line:
                    continue
                # Try to parse old format: "content|timestamp|id" or just "content"
                parts = line.split("|")
                content = parts[0].strip() if parts else line
                ts = parts[1].strip() if len(parts) > 1 else _utcnow_iso()
                mid = parts[2].strip() if len(parts) > 2 else uuid.uuid4().hex

                norm = _strip_for_embedding(content)
                ch = _hashlib.sha256(norm.encode("utf-8")).hexdigest()

                # Insert without embedding first (will be embedded lazily on search)
                self._db.execute(
                    "INSERT OR IGNORE INTO vectors (id, kind, channel_id, guild_id, "
                    "author, author_id, source, content, content_hash, embedding, "
                    "metadata, scope, importance, parent_id, chunk_index, downvotes, "
                    "timestamp, created_at) "
                    "VALUES (?, 'ltm', '', '', '', '', 'user', ?, ?, NULL, '{}', "
                    "'global', 5, '', 0, 0, ?, ?)",
                    (mid, content[:MAX_MEMORY_CHARS], ch, ts, time.time()),
                )
                migrated += 1
            if migrated:
                logger.info(f"Migrated {migrated} LTM lines from long_term_memory.txt")
                # Embed them in background
                self._spawn(self._embed_pending("ltm"))
        except Exception as e:
            logger.warning(f"LTM migration failed: {e}")

    def _migrate_shared_context(self):
        """One-time migration of shared_context.json into the vector DB."""
        sc_file = self.data_dir / "shared_context.json"
        if not sc_file.exists():
            return
        try:
            row = self._db.execute(
                "SELECT COUNT(*) as c FROM vectors WHERE kind='shared_context'"
            ).fetchone()
            if row and row["c"] > 0:
                return  # already migrated
        except Exception:
            pass

        try:
            data = json.loads(sc_file.read_text(encoding="utf-8"))
            if not isinstance(data, list):
                return
            migrated = 0
            for entry in data:
                if not isinstance(entry, dict):
                    continue
                cid = str(entry.get("id") or uuid.uuid4().hex)
                content = str(entry.get("content") or "")[:1200]
                scope = str(entry.get("scope") or "global")
                importance = int(entry.get("importance") or 5)
                ts = str(entry.get("timestamp") or _utcnow_iso())
                metadata = json.dumps(
                    {
                        k: v
                        for k, v in entry.items()
                        if k
                        not in ("id", "content", "scope", "importance", "timestamp")
                    }
                )
                self._db.execute(
                    "INSERT OR IGNORE INTO vectors (id, kind, channel_id, author, author_id, content, embedding, metadata, scope, importance, timestamp, created_at) VALUES (?, 'shared_context', '', '', '', ?, NULL, ?, ?, ?, ?, ?)",
                    (cid, content, metadata, scope, importance, ts, time.time()),
                )
                migrated += 1
            if migrated:
                logger.info(f"Migrated {migrated} shared context entries")
                self._spawn(self._embed_pending("shared_context"))
        except Exception as e:
            logger.warning(f"Shared context migration failed: {e}")

    # ─── embedding ──────────────────────────────────────────────────

    async def _embed(self, text: str) -> np.ndarray | None:
        """Generate embedding via ollama, cached on disk to SQLite.

        Cache key is md5(normalized_text). The cache survives bot
        restarts and is shared across processes (admin API, one-off
        scripts) since it lives in the same SQLite db.

        Cold call: ~138ms (ollama warmup).
        Cache hit: ~0.5ms (SQLite SELECT).
        """
        text = str(text or "").strip()
        if not text:
            return None
        # Truncate very long text before embedding
        if len(text) > 8000:
            text = text[:8000]

        import hashlib

        cache_key = hashlib.md5(text.encode()).hexdigest()

        # ─── disk cache hit ─────────────────────────────────────────
        try:
            cached = self._db.execute(
                "SELECT embedding FROM embed_cache WHERE key=? AND dim=?",
                (cache_key, EMBED_DIM),
            ).fetchone()
            if cached and cached["embedding"]:
                vec = _blob_to_embedding(cached["embedding"])
                if len(vec) == EMBED_DIM:
                    # Bump last_used_at + hits so LRU keeps useful entries.
                    try:
                        self._db.execute(
                            "UPDATE embed_cache SET last_used_at=?, hits=hits+1 "
                            "WHERE key=? AND dim=?",
                            (time.time(), cache_key, EMBED_DIM),
                        )
                    except Exception:
                        pass
                    return vec
        except Exception:
            pass

        payload = {"model": EMBED_MODEL, "input": text}

        try:
            async with self._embed_semaphore:
                async with aiohttp.ClientSession() as session:
                    async with session.post(
                        OLLAMA_EMBED_URL,
                        json=payload,
                        timeout=aiohttp.ClientTimeout(total=30),
                    ) as resp:
                        if resp.status != 200:
                            body = await resp.text()
                            logger.warning(
                                f"Embedding API returned {resp.status}: {body[:200]}"
                            )
                            return None
                        data = await resp.json()
                        embeddings = data.get("embeddings") or []
                        if not embeddings:
                            emb = data.get("embedding")
                            if emb:
                                embeddings = [emb]
                        if not embeddings:
                            logger.warning("Embedding API returned no embeddings")
                            return None
                        vec = np.array(embeddings[0], dtype=np.float32)
                        if len(vec) != EMBED_DIM:
                            logger.warning(
                                f"Embedding dimension mismatch: {len(vec)} != {EMBED_DIM}"
                            )
                            return None

                        # ─── persist to cache ─────────────────────
                        try:
                            self._db.execute(
                                "INSERT OR REPLACE INTO embed_cache "
                                "(key, dim, embedding, created_at, last_used_at, hits) "
                                "VALUES (?, ?, ?, ?, ?, COALESCE("
                                "  (SELECT hits FROM embed_cache WHERE key=? AND dim=?),"
                                "  0) + 1)",
                                (
                                    cache_key,
                                    EMBED_DIM,
                                    _embedding_to_blob(vec),
                                    time.time(),
                                    time.time(),
                                    cache_key,
                                    EMBED_DIM,
                                ),
                            )
                            self._maybe_prune_embed_cache()
                        except Exception:
                            pass  # cache write failure is non-fatal

                        return vec
        except asyncio.TimeoutError:
            logger.warning("Embedding API timeout")
            return None
        except Exception as e:
            logger.warning(f"Embedding failed: {e}")
            return None

    def _maybe_prune_embed_cache(self):
        """Cap the on-disk embed cache at 10k entries by LRU eviction.

        Rate-limited to once per 60s via `_last_embed_cache_prune` so
        heavy traffic doesn't slam SQLite with DELETE sweeps.
        """
        try:
            now = time.time()
            if getattr(self, "_last_embed_cache_prune", 0.0) + 60 > now:
                return
            self._last_embed_cache_prune = now

            cap = 10000
            cur = self._db.execute("SELECT COUNT(*) as c FROM embed_cache").fetchone()
            n = cur["c"] if cur else 0
            if n <= cap:
                return

            excess = n - cap
            self._db.execute(
                "DELETE FROM embed_cache WHERE key IN ("
                "SELECT key FROM embed_cache ORDER BY last_used_at ASC "
                "LIMIT ?)",
                (excess,),
            )
        except Exception:
            pass

