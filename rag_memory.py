    async def get_relevant_shared_context(
        self,
        user_id: str = "",
        guild_id: str = "",
        channel_id: str = "",
        is_dm: bool = False,
        is_admin: bool = False,
        max_items: int = 10,
    ) -> list[dict]:
        """Return shared context entries relevant to the current context.

        Filters by scope (user/channel/guild/global) and returns the most
        important entries. With RAG, this could also do semantic search
        but we keep scope-based filtering for shared context since it's
        already structured.
        """
        scopes = ["global"]
        if guild_id:
            scopes.append(f"guild:{guild_id}")
        if channel_id:
            scopes.append(f"channel:{channel_id}")
        if user_id:
            scopes.append(f"user:{user_id}")
        if is_dm and user_id:
            scopes.append(f"dm:{user_id}")

        placeholders = ",".join("?" * len(scopes))
        rows = self._db.execute(
            f"SELECT id, content, scope, importance, timestamp, metadata FROM vectors WHERE kind='shared_context' AND scope IN ({placeholders}) ORDER BY importance DESC, created_at DESC LIMIT ?",
            (*scopes, max_items * 2),
        ).fetchall()

        result = []
        for row in rows:
            entry = {
                "id": row["id"],
                "content": row["content"],
                "scope": row["scope"],
                "importance": row["importance"],
                "timestamp": row["timestamp"],
            }
            try:
                meta = json.loads(row["metadata"] or "{}")
                entry.update(meta)
            except Exception:
                pass
            result.append(entry)

        # Filter DM-to-admin-only
        if not is_admin:
            result = [
                e
                for e in result
                if not str(e.get("scope", "")).startswith("dm:")
                or str(e.get("scope", "")) == f"dm:{user_id}"
            ]

        return result[:max_items]

    # ─── RAG search (new) ─────────────────────────────────────────

    async def rag_search(
        self,
        query: str,
        kinds: list[str] | None = None,
        channel_id: str = "",
        top_k: int = 10,
        min_similarity: float = SIM_THRESHOLD,
    ) -> list[dict]:
        """Semantic search across the vector store.

        Args:
            query: search text
            kinds: filter by kind ('message', 'ltm', 'shared_context')
            channel_id: filter messages by channel
            top_k: max results
            min_similarity: cosine similarity cutoff

        Returns list of dicts with: id, kind, content, author, channel_id,
            timestamp, similarity, metadata
        """
        query_vec = await self._embed(query)
        if query_vec is None:
            return []

        # Build query
        where_parts = ["embedding IS NOT NULL"]
        params = []
        if kinds:
            placeholders = ",".join("?" * len(kinds))
            where_parts.append(f"kind IN ({placeholders})")
            params.extend(kinds)
        if channel_id:
            where_parts.append("(channel_id=? OR channel_id='')")
            params.append(str(channel_id))

        where_clause = " AND ".join(where_parts)
        rows = self._db.execute(
            f"SELECT id, kind, channel_id, author, author_id, content, embedding, metadata, scope, importance, timestamp FROM vectors WHERE {where_clause}",
            params,
        ).fetchall()

        if not rows:
            return []

        # Compute cosine similarity for all rows
        results = []
        query_norm = query_vec / (np.linalg.norm(query_vec) + 1e-8)
        for row in rows:
            blob = row["embedding"]
            if not blob:
                continue
            try:
                vec = _blob_to_embedding(blob)
                if len(vec) != EMBED_DIM:
                    continue
                vec_norm = vec / (np.linalg.norm(vec) + 1e-8)
                sim = float(np.dot(query_norm, vec_norm))
                if sim >= min_similarity:
                    entry = {
                        "id": row["id"],
                        "kind": row["kind"],
                        "channel_id": row["channel_id"],
                        "author": row["author"],
                        "author_id": row["author_id"],
                        "content": row["content"],
                        "scope": row["scope"],
                        "importance": row["importance"],
                        "timestamp": row["timestamp"],
                        "similarity": sim,
                    }
                    try:
                        meta = json.loads(row["metadata"] or "{}")
                        entry.update(meta)
                    except Exception:
                        pass
                    results.append(entry)
            except Exception:
                continue

        # Sort by similarity descending, take top_k
        results.sort(key=lambda x: x["similarity"], reverse=True)
        return results[:top_k]

    async def rag_relevant_context(
        self,
        query: str,
        channel_id: str = "",
        top_k: int = 15,
    ) -> list[dict]:
        """Get semantically relevant context for a user message.

        Searches across messages, LTM, and shared context. Returns a
        mixed list of the most semantically relevant entries, useful
        for augmenting the system prompt with RAG context.
        """
        results = await self.rag_search(
            query,
            kinds=["message", "ltm", "shared_context"],
            channel_id=channel_id,
            top_k=top_k * 3,  # over-fetch then dedupe/diversify
        )

        # Deduplicate by content similarity (avoid returning near-identical messages)
        seen = set()
        deduped = []
        for r in results:
            key = r["content"][:200].lower()
            if key not in seen:
                seen.add(key)
                deduped.append(r)

        # Diversify: ensure we get a mix of kinds
        by_kind = {"message": [], "ltm": [], "shared_context": []}
        for r in deduped:
            by_kind.setdefault(r["kind"], []).append(r)

        mixed = []
        # Prioritize LTM and shared_context (durable facts) then messages
        for kind in ("ltm", "shared_context", "message"):
            mixed.extend(by_kind.get(kind, [])[: top_k // 2])

        return mixed[:top_k]

